#!/usr/bin/env node
// Bundles src/submission-check.ts (the Worker's output checks) into one ESM file
// for the agent image, where `ack3-submit` and the runner use it. The bundle is
// committed; test/submission-check-bundle.test.ts fails when it is stale.
// Usage: node tools/build-submission-check.mjs
import { createRequire } from 'node:module'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const engine = fileURLToPath(new URL('..', import.meta.url))
export const submissionCheckBundlePath = `${engine}container/submission-check.bundle.mjs`

export async function buildSubmissionCheckBundle() {
  // esbuild comes with the pinned wrangler devDependency, so this needs no dependency of its own.
  const esbuild = createRequire(createRequire(import.meta.url).resolve('wrangler/package.json'))('esbuild')
  const result = await esbuild.build({
    entryPoints: ['src/submission-check.ts'], absWorkingDir: engine, bundle: true, write: false,
    format: 'esm', platform: 'node', target: 'node22', legalComments: 'eof', logLevel: 'silent', metafile: true,
    banner: { js: '// Generated by tools/build-submission-check.mjs from src/submission-check.ts. Do not edit.' },
  })
  // esbuild names dependencies by their path from the engine, and pnpm's store may
  // sit in a parent checkout: keep only the store-relative part so every checkout builds the same bytes.
  const bundle = result.outputFiles[0].text.replace(/(?:\.\.\/)+(?:[\w.-]+\/)*node_modules\/\.pnpm\//g, 'node_modules/.pnpm/')
  return `${bundle}${await thirdPartyNotices(Object.keys(result.metafile.inputs))}`
}

// MIT and BSD licenses require their notices in every copy: append each bundled
// package's own license text, sorted, so the bundle stays byte-for-byte reproducible.
async function thirdPartyNotices(inputs) {
  const roots = new Set(inputs.flatMap(input => input.match(/^(.*\/node_modules\/(?:@[^/]+\/)?[^/]+)\//)?.[1] ?? []))
  const packages = await Promise.all([...roots].map(async root => {
    const directory = resolve(engine, root)
    const manifest = JSON.parse(await readFile(`${directory}/package.json`, 'utf8'))
    const license = (await readdir(directory)).filter(name => /^licen[cs]e(-[a-z0-9]+)?(\.(md|txt))?$/i.test(name)).sort()[0]
    if (license === undefined) throw new Error(`bundled package ${manifest.name} has no license file`)
    return { name: manifest.name, version: manifest.version, license: manifest.license,
      text: (await readFile(`${directory}/${license}`, 'utf8')).trim().replaceAll('*/', '* /') }
  }))
  if (packages.length === 0) return ''
  return `\n/* Third-party code in this bundle, with each package's license:\n${packages
    .sort((left, right) => left.name < right.name ? -1 : left.name > right.name ? 1 : 0)
    .map(item => `\n${item.name} ${item.version} (${item.license})\n\n${item.text}\n`).join('')}*/\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(submissionCheckBundlePath, await buildSubmissionCheckBundle())
  console.log(`wrote ${submissionCheckBundlePath}`)
}
